NSIS_TEMPLATE = r"""; NSIS Installer Script
; Auto-generated by AICluster build system. DO NOT EDIT BY HAND.

!define APP_NAME "{product_name}"
!define APP_VERSION "{version}"
!define APP_PUBLISHER "{company}"
!define APP_EXE "{exe_name}"
!define APP_ID "{app_id}"

Name "${{APP_NAME}} ${{APP_VERSION}}"
OutFile "..\installer\{product_name}-Setup-{version}.exe"
InstallDir "$PROGRAMFILES64\${{APP_NAME}}"
RequestExecutionLevel user

Unicode True
SetCompressor /SOLID lzma

!include "MUI2.nsh"
!include "LogicLib.nsh"

!define MUI_ABORTWARNING
!define MUI_ICON "{icon}"
!define MUI_UNICON "{icon}"

!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_LANGUAGE "English"

Section "Install"
  SetOutPath "$INSTDIR"
  File /r "{source_dir}\*"
  CreateShortcut "$DESKTOP\${{APP_NAME}}.lnk" "$INSTDIR\${{APP_EXE}}"
  CreateDirectory "$SMPROGRAMS\${{APP_NAME}}"
  CreateShortcut "$SMPROGRAMS\${{APP_NAME}}\${{APP_NAME}}.lnk" "$INSTDIR\${{APP_EXE}}"
  WriteUninstaller "$INSTDIR\Uninstall.exe"
SectionEnd

Section "Uninstall"
  Delete "$INSTDIR\${{APP_EXE}}"
  RMDir /r "$INSTDIR"
  Delete "$DESKTOP\${{APP_NAME}}.lnk"
  Delete "$SMPROGRAMS\${{APP_NAME}}\${{APP_NAME}}.lnk"
  RMDir "$SMPROGRAMS\${{APP_NAME}}"
SectionEnd
"""


@dataclass
class ReleaseReport:
    version: str
    installers: Dict[str, List[Path]] = field(default_factory=dict)
    build_report: Optional[Path] = None
    release_notes: Optional[Path] = None
    signed: List[str] = field(default_factory=list)
    notes: List[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "version": self.version,
            "installers": {k: [str(p) for p in v]
                           for k, v in self.installers.items()},
            "build_report": str(self.build_report) if self.build_report else None,
            "release_notes": str(self.release_notes) if self.release_notes else None,
            "signed": self.signed,
            "notes": self.notes,
        }


def _all_release_targets() -> list:
    return list(PYINSTALLER_TARGETS) + list(TAURI_TARGETS)


def _icon_path(target) -> Optional[Path]:
    if target.icon and target.icon.exists():
        return target.icon
    candidate = ICONS_DIR / "default.ico"
    return candidate if candidate.exists() else None


def _app_id(target) -> str:
    base = target.output_name.replace(".exe", "").lower()
    return f"com.aicluster.{base}"


def _write_iss(target, source_dir: Path, version: VersionInfo) -> Path:
    installer_dir = RELEASE_LAYOUT["installer"] / target.key
    installer_dir.mkdir(parents=True, exist_ok=True)
    iss = installer_dir / "installer.iss"
    iss.write_text(
        INNO_SETUP_TEMPLATE.format(
            product_name=version.product_name,
            version=version.version,
            company=version.company,
            copyright=version.copyright,
            exe_name=target.output_name,
            app_id=_app_id(target),
            icon=str(_icon_path(target) or ""),
            source_dir=str(source_dir).replace("/", "\\"),
        ),
        encoding="utf-8",
    )
    log.info("wrote %s", iss)
    return iss


def _write_nsi(target, source_dir: Path, version: VersionInfo) -> Path:
    installer_dir = RELEASE_LAYOUT["installer"] / target.key
    installer_dir.mkdir(parents=True, exist_ok=True)
    nsi = installer_dir / "installer.nsi"
    nsi.write_text(
        NSIS_TEMPLATE.format(
            product_name=version.product_name,
            version=version.version,
            company=version.company,
            exe_name=target.output_name,
            app_id=_app_id(target),
            icon=str(_icon_path(target) or ""),
            source_dir=str(source_dir).replace("/", "\\"),
        ),
        encoding="utf-8",
    )
    log.info("wrote %s", nsi)
    return nsi


def _maybe_compile_inno(iss: Path) -> Optional[Path]:
    iscc = shutil.which("iscc")
    if not iscc:
        candidates = []
        for env in ("ProgramFiles(x86)", "ProgramFiles"):
            base = Path(os.environ.get(env, str(Path.home() / env))) / "Inno Setup"
            for sub in base.glob("ISCC.exe"):
                candidates.append(sub)
        if candidates:
            iscc = str(candidates[0])
    if not iscc:
        log.info("Inno Setup compiler not found — skipping compilation")
        return None
    cmd = [iscc, str(iss)]
    log.info("compiling %s with %s", iss.name, iscc)
    proc = subprocess.run(cmd, cwd=iss.parent, capture_output=True, text=True)
    if proc.returncode != 0:
        log.error("ISCC failed: %s", proc.stderr)
        return None
    out = iss.parent.parent / (iss.stem + "-Setup.exe")
    if not out.exists():
        for cand in iss.parent.glob("Output/*.exe"):
            out = cand
            break
    return out if out.exists() else None


def _maybe_compile_nsis(nsi: Path) -> Optional[Path]:
    makensis = shutil.which("makensis")
    if not makensis:
        for env in ("ProgramFiles(x86)", "ProgramFiles"):
            base = Path(os.environ.get(env, str(Path.home() / env))) / "NSIS"
            for cand in base.rglob("makensis.exe"):
                makensis = str(cand)
                break
        if not makensis:
            log.info("NSIS not found — skipping compilation")
            return None
    cmd = [makensis, str(nsi)]
    log.info("compiling %s with %s", nsi.name, makensis)
    proc = subprocess.run(cmd, cwd=nsi.parent, capture_output=True, text=True)
    if proc.returncode != 0:
        log.error("makensis failed: %s", proc.stderr)
        return None
    out = nsi.parent.parent / (Path(nsi.stem + "-Setup.exe").name)
    return out if out.exists() else None


def generate_installers(
    cfg: Optional[BuildConfig] = None,
) -> Dict[str, List[Path]]:
    cfg = cfg or BuildConfig()
    setup_logging(cfg.log_level)
    version = resolve_version()

    installers: Dict[str, List[Path]] = {}
    for target in _all_release_targets():
        source = RELEASE_DIR / target.output_subdir
        if not source.exists():
            log.info("[%s] no release output, skipping installer scripts",
                     target.name)
            continue
        iss = _write_iss(target, source, version)
        nsi = _write_nsi(target, source, version)
        results: List[Path] = [iss, nsi]
        if not cfg.skip_installer:
            if compiled := _maybe_compile_inno(iss):
                results.append(compiled)
            if compiled := _maybe_compile_nsis(nsi):
                results.append(compiled)
        installers[target.key] = results
    return installers


def _read_changelog(version: str) -> Optional[str]:
    path = RELEASE_DIR.parent / "CHANGELOG.md"
    if not path.exists():
        return None
    text = path.read_text(encoding="utf-8")
    needle = f"## v{version}"
    if needle not in text:
        return text[:2000]
    start = text.index(needle)
    rest = text[start:]
    next_break = rest.find("\n## ")
    return rest if next_break == -1 else rest[:next_break]


def write_release_notes(
    report_payload: dict,
    cfg: Optional[BuildConfig] = None,
) -> Path:
    cfg = cfg or BuildConfig()
    setup_logging(cfg.log_level)
    version = resolve_version()
    notes = _read_changelog(version.version) or "(no CHANGELOG entries)"

    out = RELEASE_DIR / "RELEASE_NOTES.md"
    body = (
        f"# {version.product_name} v{version.version}\n\n"
        f"_Build date: {version.build_date}_\n\n"
        f"## Changelog Excerpt\n\n{notes}\n\n"
        f"## Artifacts\n\n"
    )
    for app, info in report_payload.get("apps", {}).items():
        primary = info.get("primary", {})
        body += (
            f"- **{info.get('name', app)}** — "
            f"`{info.get('output', '?')}` "
            f"({primary.get('size', '?')} bytes, "
            f"sha256 `{primary.get('sha256', '?')[:16]}…`)\n"
        )
    out.write_text(body, encoding="utf-8")
    log.info("wrote %s", out)
    return out


def write_build_report(
    *,
    duration_seconds: float,
    env_report: dict,
    artifacts: dict,
    package_report: dict,
    installer_report: dict,
    signed: List[str],
    warnings: List[str],
    errors: List[str],
    cfg: Optional[BuildConfig] = None,
) -> Path:
    cfg = cfg or BuildConfig()
    version = resolve_version()

    def fmt_size(n: int) -> str:
        units = ["B", "KB", "MB", "GB"]
        size = float(n)
        for u in units:
            if size < 1024:
                return f"{size:.1f} {u}"
            size /= 1024
        return f"{size:.1f} TB"

    lines: List[str] = []
    lines.append(f"# {version.product_name} v{version.version} — Build Report")
    lines.append("")
    lines.append(f"**Build date:** {version.build_date}  ")
    lines.append(f"**Duration:** {duration_seconds:.1f} s  ")
    lines.append(f"**Company:** {version.company}  ")
    lines.append(f"**Copyright:** {version.copyright}  ")
    if version.git_tag:
        lines.append(f"**Git tag:** {version.git_tag}  ")
    lines.append("")
    lines.append("## Tooling")
    lines.append("")
    lines.append("| Tool | Version | Path |")
    lines.append("|------|---------|------|")
    for tool in env_report.get("tools", []):
        lines.append(
            f"| {tool['name']} | {tool.get('version', '?') or '?'} | "
            f"`{tool.get('path', '')}` |"
        )
    lines.append("")
    lines.append("## Artifacts")
    lines.append("")
    lines.append("| App | Output | Size | SHA-256 |")
    lines.append("|-----|--------|------|---------|")
    for key, info in package_report.get("apps", {}).items():
        primary = info.get("primary", {})
        lines.append(
            f"| {info.get('name', key)} | `{info.get('output', '?')}` | "
            f"{fmt_size(primary.get('size', 0))} | "
            f"`{primary.get('sha256', '?')}` |"
        )
    lines.append("")
    lines.append("## Checksums")
    lines.append("")
    lines.append(f"- `release/checksums/checksums.txt`")
    lines.append(f"- `release/checksums/manifest.json`")
    lines.append("")
    lines.append("## Installers")
    lines.append("")
    for key, paths in installer_report.get("installers", {}).items():
        lines.append(f"### {key}")
        for p in paths:
            lines.append(f"- `{p}`")
        lines.append("")
    if signed:
        lines.append("## Signed Artifacts")
        for s in signed:
            lines.append(f"- {s}")
        lines.append("")
    if warnings:
        lines.append("## Warnings")
        for w in warnings:
            lines.append(f"- {w}")
        lines.append("")
    if errors:
        lines.append("## Errors")
        for e in errors:
            lines.append(f"- {e}")
        lines.append("")

    out = RELEASE_LAYOUT["reports"] / "build-report.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    log.info("wrote %s", out)
    return out


def release(
    *,
    env_report: dict,
    artifacts: dict,
    package_report: dict,
    duration_seconds: float,
    signed: List[str],
    warnings: List[str],
    errors: List[str],
    cfg: Optional[BuildConfig] = None,
) -> ReleaseReport:
    cfg = cfg or BuildConfig()
    setup_logging(cfg.log_level)
    version = resolve_version()

    installers = generate_installers(cfg)
    release_notes = write_release_notes(package_report, cfg)
    report = write_build_report(
        duration_seconds=duration_seconds,
        env_report=env_report,
        artifacts=artifacts,
        package_report=package_report,
        installer_report={"installers": {k: [str(p) for p in v]
                                        for k, v in installers.items()}},
        signed=signed,
        warnings=warnings,
        errors=errors,
        cfg=cfg,
    )

    return ReleaseReport(
        version=version.version,
        installers=installers,
        build_report=report,
        release_notes=release_notes,
        signed=signed,
    )


