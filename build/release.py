"""Installer script generation and release notes.

This module is *not* responsible for actually compiling installers — it
generates the source scripts (Inno Setup ``.iss`` and NSIS ``.nsi``)
plus a Markdown build report. The build system will run the compiler
if it is available and silently skip it otherwise.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Dict, List, Optional

from .config import (
    ICONS_DIR,
    RELEASE_DIR,
    PYINSTALLER_TARGETS,
    TAURI_TARGETS,
    BuildConfig,
    RELEASE_LAYOUT,
    is_windows,
)
from .logger import setup_logging, get_logger
from .version import VersionInfo, resolve_version

log = get_logger("aicluster.build.release")


