"""Remove transient build artifacts.

Usage::

    python -m build.clean            # remove transient directories
    python -m build.clean --all      # also wipe release/, dist/, artifacts/
    python -m build.clean --pyc      # also delete __pycache__ folders
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path
from typing import List

from .config import (
    ARTIFACTS_DIR,
    DIST_DIR,
    REPO_ROOT,
    RELEASE_DIR,
    TEMP_DIR,
    LOGS_DIR,
    CHECKSUMS_DIR,
    BuildConfig,
    all_release_subdirs,
    PYINSTALLER_TARGETS,
    TAURI_TARGETS,
)
from .logger import setup_logging, get_logger

log = get_logger("aicluster.build.clean")


def _remove_dir(path: Path) -> None:
    if not path.exists():
        return
    if not path.is_dir():
        log.warning("skipping non-directory: %s", path)
        return
    log.info("removing %s", path)
    try:
        shutil.rmtree(path, ignore_errors=True)
    except OSError as exc:
        log.warning("could not fully remove %s: %s", path, exc)


def _remove_pyc(root: Path) -> int:
    count = 0
    for cache in root.rglob("__pycache__"):
        if cache.is_dir():
            shutil.rmtree(cache, ignore_errors=True)
            count += 1
    for pyc in root.rglob("*.pyc"):
        try:
            pyc.unlink()
            count += 1
        except OSError:
            pass
    return count


def run(include_release: bool = False, include_pyc: bool = False,
        include_logs: bool = False) -> int:
    setup_logging(BuildConfig().log_level)

    targets: List[Path] = [TEMP_DIR, DIST_DIR, ARTIFACTS_DIR, CHECKSUMS_DIR]
    if include_release:
        targets.append(RELEASE_DIR)
        targets.extend(all_release_subdirs())
    if include_logs:
        targets.append(LOGS_DIR)

    for path in targets:
        _remove_dir(path)

    # Always clean the per-target dist folders generated by PyInstaller / Tauri
    for t in PYINSTALLER_TARGETS:
        spec = t.entry.with_name(t.entry.stem + ".spec")
        if spec.exists():
            log.info("removing spec: %s", spec)
            try:
                spec.unlink()
            except OSError:
                pass
        build = t.entry.parent / "build"
        _remove_dir(build)
        pycache = t.entry.parent / "__pycache__"
        _remove_dir(pycache)

    for t in TAURI_TARGETS:
        for sub in ("target", "dist"):
            _remove_dir(t.frontend_dir / sub)
            _remove_dir(t.tauri_config_dir / sub)

    removed_pyc = 0
    if include_pyc:
        removed_pyc = _remove_pyc(REPO_ROOT)
        log.info("removed %d __pycache__ / .pyc entries", removed_pyc)

    log.info("clean complete")
    return 0


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Clean AICluster build artifacts")
    parser.add_argument("--all", action="store_true",
                        help="also wipe release/ tree")
    parser.add_argument("--pyc", action="store_true",
                        help="also remove __pycache__ folders under the repo")
    parser.add_argument("--logs", action="store_true",
                        help="also wipe logs/ directory")
    args = parser.parse_args(argv)
    return run(include_release=args.all, include_pyc=args.pyc,
               include_logs=args.logs)


if __name__ == "__main__":
    sys.exit(main())
