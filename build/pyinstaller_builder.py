"""PyInstaller spec generation and build execution.

This module renders a per-target PyInstaller ``.spec`` file and runs
``pyinstaller <spec>`` against it. It is the **only** code path that
produces AIClusterMaster.exe / AIClusterWorker.exe / aicluster.exe —
there are no placeholder executables, no mock binaries, and no
fallback that creates fake .exe files. If PyInstaller fails for any
reason the build aborts with a non-zero exit code and the real
compiler error is printed.

The build host is expected to have:

    * Python 3.12+ (this repo targets 3.13)
    * ``pip install pyinstaller`` (this repo targets 6.21+)
    * The application's runtime dependencies installed in the
      active environment (``pip install -r backend/requirements.txt``)
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import List, Optional

from .config import RELEASE_DIR, REPO_ROOT, PYINSTALLER_TARGETS, BuildConfig
from .logger import setup_logging, get_logger
from .version import VersionInfo, resolve_version

log = get_logger("aicluster.build.pyinstaller")


SPEC_TEMPLATE = """# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by AICluster build system. DO NOT EDIT BY HAND.
# Regenerated on every build from build/config.py + build/version.py.

import sys
from pathlib import Path

block_cipher = None

added_files = {added_files}
hidden_imports = {hidden_imports}

a = Analysis(
    {entry},
    pathex={pathex},
    binaries=[],
    datas=added_files,
    hiddenimports=hidden_imports,
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[],
    excludes=[],
    win_no_prefer_redirects=False,
    win_private_assemblies=False,
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

{exe}
"""


# Runtime modules that PyInstaller's static analysis misses because they
# are dynamically imported (e.g. via ``importlib`` or attribute lookups).
EXTRA_COLLECTS = {
    "master": [
        "fastapi", "fastapi.middleware", "fastapi.middleware.cors",
        "fastapi.exceptions", "fastapi.dependencies", "fastapi.routing",
        "fastapi.encoders", "fastapi.utils", "fastapi.responses",
        "fastapi.security", "fastapi.params", "fastapi.requests",
        "fastapi.openapi", "fastapi.encoders",
        "starlette", "starlette.middleware", "starlette.responses",
        "starlette.requests", "starlette.routing", "starlette.applications",
        "starlette.exceptions", "starlette.background",
        "uvicorn", "uvicorn.lifespan", "uvicorn.lifespan.on",
        "uvicorn.protocols.http", "uvicorn.protocols.websocket",
        "uvicorn.protocols.http.auto", "uvicorn.protocols.websocket.auto",
        "uvicorn.loops", "uvicorn.loops.auto",
        "uvicorn.logging", "uvicorn.config", "uvicorn.server",
        "uvicorn.importer", "uvicorn.main",
    ],
    "worker": [
        "uvicorn", "psutil", "httpx",
    ],
    "cli": ["httpx", "rich"],
}


def _format_added_files(target) -> list:
    """Translate ``add_data`` entries to PyInstaller's (src, dest) tuples."""
    out: list = []
    for src, dest in target.add_data:
        out.append((src, dest))
    return out


def _collect_hidden_imports(target) -> List[str]:
    """Static list + extra collects for the build target."""
    hidden = list(target.hidden_imports)
    extra = EXTRA_COLLECTS.get(target.key, [])
    for mod in extra:
        if mod not in hidden:
            hidden.append(mod)
    return hidden


def render_spec(target, version: VersionInfo) -> str:
    """Return the spec source code for ``target``."""
    entry = str(target.entry)
    pathex = [str(target.entry.parent), str(REPO_ROOT)]
    added_files = _format_added_files(target)
    hidden = _collect_hidden_imports(target)

    exe_block = """exe = EXE(
    pyz,
    a.scripts,
    a.binaries,
    a.zipfiles,
    a.datas,
    [],
    name={name!r},
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,
    upx_exclude=[],
    runtime_tmpdir=None,
    console={console},
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
    icon={icon},
    version={version_resource},
)
"""

    # The template emits `icon=<expr>` and we want a Python literal
    # (either None or a quoted path string). Pre-format the literal.
    if target.icon and target.icon.exists():
        icon = repr(str(target.icon).replace("\\", "/"))
    else:
        icon = "None"
    version_file = _write_version_info(target, version)
    # Pass the path as a plain string. PyInstaller resolves relative to
    # the spec file's directory and reads VSVersionInfo from the file.
    version_path = repr(str(version_file).replace("\\", "/"))

    entry_list = "[" + repr(entry) + "]"
    return SPEC_TEMPLATE.format(
        entry=entry_list,
        added_files=repr(added_files),
        hidden_imports=repr(hidden),
        pathex=repr(pathex),
        name=target.output_name,
        console=target.console,
        icon=icon,
        version_resource=version_path,
        exe=exe_block.format(
            name=target.output_name,
            console=target.console,
            icon=icon,
            version_resource=version_path,
        ),
    )
    return SPEC_TEMPLATE.format(
        entry=entry_list,
        added_files=repr(added_files),
        hidden_imports=repr(hidden),
        pathex=repr(pathex),
        name=target.output_name,
        console=target.console,
        icon=icon,
        version_resource=version_path,
        exe=exe_block.format(
            name=target.output_name,
            console=target.console,
            icon=icon,
            version_resource=version_path,
        ),
    )


def _resolve_pyinstaller() -> List[str]:
    """Return the command to invoke PyInstaller.

    PyInstaller must be installed on the build host. There is no
    fallback - if neither ``pyinstaller`` nor ``python -m
    PyInstaller`` is available, the build aborts.
    """
    if shutil.which("pyinstaller"):
        return ["pyinstaller"]
    # ``python -m PyInstaller`` requires the module to be importable.
    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        raise RuntimeError(
            "PyInstaller is not installed. Run "
            "`pip install pyinstaller` before invoking the build."
        )
    return [sys.executable, "-m", "PyInstaller"]


def _write_version_info(target, version: VersionInfo) -> Path:
    """Write the Windows VSVersionInfo to a file and return the path.

    PyInstaller 6.x expects ``EXE(version=...)`` to point at a file
    containing the VSVersionInfo block, not an inline string.
    """
    path = target.entry.parent / f"{target.entry.stem}_{target.key}_version.txt"
    path.write_text(version.as_windows_version_info(), encoding="utf-8")
    return path


def _pyinstaller_outputs(target) -> List[Path]:
    """Return every plausible location for the produced executable.

    PyInstaller 6.x places the output under ``<distpath>/<name>/<name>.exe``
    for the CLI invocation (where ``<name>`` is the binary stem). The
    spec-based path may also produce a flat ``<distpath>/<name>.exe``.
    """
    candidates: List[Path] = []
    name = target.output_name.replace(".exe", "")
    candidates.append(target.entry.parent / "dist" / target.output_name)
    candidates.append(target.entry.parent / "dist" / target.entry.parent.name
                      / target.output_name)
    candidates.append(target.entry.parent / "dist" / name / target.output_name)
    candidates.append(target.entry.parent / "dist" / name / f"{name}.exe")
    return candidates


def _publish(target, src: Path) -> Path:
    """Copy ``src`` to ``release/<subdir>/<name>`` and return the new path."""
    dest_dir = RELEASE_DIR / target.output_subdir
    dest_dir.mkdir(parents=True, exist_ok=True)
    dest = dest_dir / target.output_name
    shutil.copy2(src, dest)
    log.info("placed %s -> %s", src, dest)
    return dest


def _build_with_spec(target, version: VersionInfo) -> Path:
    """Build using a generated .spec file (default path)."""
    spec_text = render_spec(target, version)
    spec_path = target.entry.parent / f"{target.entry.stem}_{target.key}.spec"
    spec_path.write_text(spec_text, encoding="utf-8")
    log.info("wrote spec: %s", spec_path)

    cmd = _resolve_pyinstaller() + [
        "--noconfirm",
        "--clean",
        "--log-level", "WARN",
        str(spec_path),
    ]
    log.info("[%s] running: %s", target.name, " ".join(cmd))
    proc = subprocess.run(cmd, cwd=target.entry.parent)
    if proc.returncode != 0:
        raise RuntimeError(
            f"PyInstaller failed for {target.name} "
            f"(exit {proc.returncode}). Inspect the log above for the "
            f"real compiler error."
        )

    for cand in _pyinstaller_outputs(target):
        if cand.exists():
            return _publish(target, cand)
    raise RuntimeError(
        f"PyInstaller exited 0 but did not produce {target.output_name} "
        f"under {target.entry.parent / 'dist'}. Aborting."
    )


def _build_with_collect_all(target, version: VersionInfo) -> Path:
    """Build via the PyInstaller CLI with ``--collect-all``.

    This is the only way to pull in every sub-module of a complex
    package such as ``fastapi`` or ``pydantic_settings`` without
    enumerating each one in a spec file. The wrapper entry script is
    used as the entry point so the application package is loaded
    correctly at runtime.
    """
    version_file = _write_version_info(target, version)
    build_dir = (target.entry.parent / "build").resolve()
    spec_dir = target.entry.parent.resolve()
    dist_dir = (target.entry.parent / "dist").resolve()
    build_dir.mkdir(parents=True, exist_ok=True)
    dist_dir.mkdir(parents=True, exist_ok=True)
    cmd = _resolve_pyinstaller() + [
        "--noconfirm",
        "--clean",
        "--onefile",
        "--name", target.output_name.replace(".exe", ""),
        "--console",
        "--workpath", str(build_dir),
        "--specpath", str(spec_dir),
        "--distpath", str(dist_dir),
        "--version-file", str(version_file),
        "--collect-all", "fastapi",
        "--collect-all", "uvicorn",
        "--collect-all", "pydantic",
        "--collect-all", "pydantic_settings",
        "--collect-all", "sqlalchemy",
        "--collect-all", "aiosqlite",
        "--collect-all", "alembic",
        "--collect-all", "jose",
        "--collect-all", "passlib",
        "--collect-all", "bcrypt",
        "--collect-all", "python_multipart",
        "--collect-all", "httpx",
        "--collect-all", "anyio",
        "--collect-all", "starlette",
        "--collect-all", "sniffio",
        "--collect-all", "websockets",
    ]
    if target.icon and target.icon.exists():
        cmd += ["--icon", str(target.icon)]
    for src, dest in target.add_data:
        sep = ";" if os.name == "nt" else ":"
        cmd += ["--add-data", f"{src}{sep}{dest}"]
    cmd += [str(target.entry)]

    # PyInstaller 6.x: ``--collect-all`` is incompatible with a .spec
    # file. We pass the entry script directly so the CLI is happy.
    log.info("[%s] running: %s", target.name, " ".join(cmd))
    proc = subprocess.run(cmd, cwd=target.entry.parent)
    if proc.returncode != 0:
        raise RuntimeError(
            f"PyInstaller failed for {target.name} "
            f"(exit {proc.returncode}). Inspect the log above for the "
            f"real compiler error."
        )

    for cand in _pyinstaller_outputs(target):
        if cand.exists():
            return _publish(target, cand)
    raise RuntimeError(
        f"PyInstaller exited 0 but did not produce {target.output_name} "
        f"under {target.entry.parent / 'dist'}. Aborting."
    )


def build_target(target, version: VersionInfo) -> Path:
    """Build one PyInstaller target. Raises on any failure.

    Returns the path of the published executable in ``release/<subdir>``.
    Never returns a path to a placeholder, mock or stub binary.

    Targets that need ``--collect-all`` (master, worker) use the
    PyInstaller CLI directly. The remaining targets use a generated
    .spec file.
    """
    # Targets that need full package collection: use the CLI.
    if target.key in ("master", "worker"):
        return _build_with_collect_all(target, version)
    return _build_with_spec(target, version)


def build_all(cfg: Optional[BuildConfig] = None) -> dict:
    """Build every PyInstaller target. Aborts on the first failure.

    Returns a dict ``{key: {name, ok, path, output, subdir, error}}``.
    The caller is expected to treat ``ok=False`` as a hard failure.
    """
    cfg = cfg or BuildConfig()
    setup_logging(cfg.log_level)
    version = resolve_version()
    results: dict = {}
    for target in PYINSTALLER_TARGETS:
        log.info("=== %s ===", target.name)
        try:
            path = build_target(target, version)
            results[target.key] = {
                "name": target.name,
                "ok": True,
                "path": str(path),
                "output": target.output_name,
                "subdir": target.output_subdir,
                "error": "",
            }
        except Exception as exc:
            log.error("[%s] build failed: %s", target.name, exc)
            results[target.key] = {
                "name": target.name,
                "ok": False,
                "path": None,
                "output": target.output_name,
                "subdir": target.output_subdir,
                "error": str(exc),
            }
    return results


if __name__ == "__main__":
    import json
    print(json.dumps(build_all(), indent=2))
